"""Ranked time windows: recurring schedules (stored in the DB, edited at /admin) plus fixed one-off windows."""

from __future__ import annotations

import re
import secrets
import time
from collections.abc import Sequence
from datetime import datetime, timedelta, timezone

from .config import DEFAULT_CHARACTERS, Settings
from .db import Database

# Same alphabet the game uses for seeds (SeedHelper): no O or I, so canonicalisation is a no-op.
SEED_ALPHABET = "0123456789ABCDEFGHJKLMNPQRSTUVWXYZ"
SEED_LENGTH = 12
SEED_PATTERN = re.compile(r"^[0-9A-HJ-NP-Z]{4,32}$")
SLUG_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,31}$")
WINDOW_ID_PATTERN = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
TIME_PATTERN = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")
WEEKDAY_NAMES = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")

# kind values stored in windows.kind: 'daily' = generated by a recurring schedule, 'manual' = fixed one-off.
KIND_RECURRING = "daily"
KIND_FIXED = "manual"


def random_seed() -> str:
    return "".join(secrets.choice(SEED_ALPHABET) for _ in range(SEED_LENGTH))


def now() -> int:
    return int(time.time())


def overlapping(db: Database, starts_at: int, ends_at: int, exclude_id: str | None = None) -> list:
    return db.all(
        "SELECT * FROM windows WHERE starts_at < ? AND ends_at > ? AND id IS NOT ?",
        (ends_at, starts_at, exclude_id),
    )


def create_window(
    db: Database,
    settings: Settings,
    *,
    window_id: str,
    kind: str,
    starts_at: int,
    ends_at: int,
    game_version: str | None,
    seed: str | None = None,
    character: str | None = None,
    character_pool: Sequence[str] | None = None,
    submit_grace_minutes: int | None = None,
    schedule_id: int | None = None,
) -> dict:
    grace = settings.submit_grace_minutes if submit_grace_minutes is None else submit_grace_minutes
    pool = list(character_pool or settings.characters)
    db.execute(
        "INSERT INTO windows (id, kind, starts_at, ends_at, submit_deadline, seed, setup_key, game_version, character,"
        " schedule_id, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (
            window_id,
            kind,
            starts_at,
            ends_at,
            ends_at + grace * 60,
            seed or random_seed(),
            random_seed(),
            game_version or None,
            character or secrets.choice(pool),
            schedule_id,
            now(),
        ),
    )
    return dict(db.one("SELECT * FROM windows WHERE id = ?", (window_id,)))


def fill_missing_characters(db: Database, settings: Settings) -> None:
    for row in db.all("SELECT id FROM windows WHERE character IS NULL"):
        db.execute("UPDATE windows SET character = ? WHERE id = ?", (secrets.choice(settings.characters), row["id"]))


# ---------- recurring schedules ----------


def seed_schedules_from_env(db: Database, settings: Settings) -> None:
    """One-time migration: the RANKED_DAILY_* env vars become the first schedule ("daily").

    After that the DB is the source of truth, so deleting every schedule at /admin doesn't bring it back.
    """
    with db.lock:
        if db.one("SELECT 1 FROM meta WHERE key = 'schedules_seeded'"):
            return
        if settings.daily_start and not db.one("SELECT 1 FROM schedules WHERE slug = 'daily'"):
            cur = db.execute(
                "INSERT INTO schedules (slug, start_time, duration_minutes, submit_grace_minutes, weekdays, characters,"
                " game_version, enabled, created_at) VALUES ('daily', ?, ?, ?, '0123456', ?, ?, 1, ?)",
                (
                    settings.daily_start,
                    settings.daily_duration_minutes,
                    settings.submit_grace_minutes,
                    ",".join(settings.characters) if tuple(settings.characters) != DEFAULT_CHARACTERS else None,
                    settings.game_version or None,
                    now(),
                ),
            )
            db.execute(
                "UPDATE windows SET schedule_id = ? WHERE kind = 'daily' AND schedule_id IS NULL AND id LIKE 'daily-%'",
                (cur.lastrowid,),
            )
        db.execute("INSERT INTO meta (key, value) VALUES ('schedules_seeded', '1')")


def schedule_pool(schedule: dict, settings: Settings) -> list[str]:
    if schedule.get("characters"):
        return [c for c in schedule["characters"].split(",") if c]
    return list(settings.characters)


def ensure_recurring_windows(db: Database, settings: Settings, at: int | None = None) -> None:
    """Lazily create each enabled schedule's windows for yesterday, today and tomorrow (UTC).

    Seeds and characters are fixed at creation time; seeds stay secret until a player starts a run.
    A window is skipped if it would overlap an existing one (another schedule's, or a fixed window).
    """
    at = now() if at is None else at
    today = datetime.fromtimestamp(at, tz=timezone.utc).date()
    with db.lock:
        for schedule in [dict(r) for r in db.all("SELECT * FROM schedules WHERE enabled = 1 ORDER BY id")]:
            hour, minute = (int(p) for p in schedule["start_time"].split(":"))
            for offset in (-1, 0, 1):
                day = today + timedelta(days=offset)
                if str(day.weekday()) not in schedule["weekdays"]:
                    continue
                window_id = f"{schedule['slug']}-{day.isoformat()}"
                if db.one("SELECT 1 FROM windows WHERE id = ?", (window_id,)):
                    continue
                start = int(datetime(day.year, day.month, day.day, hour, minute, tzinfo=timezone.utc).timestamp())
                end = start + schedule["duration_minutes"] * 60
                if overlapping(db, start, end):
                    continue
                create_window(
                    db,
                    settings,
                    window_id=window_id,
                    kind=KIND_RECURRING,
                    starts_at=start,
                    ends_at=end,
                    game_version=schedule["game_version"],
                    character_pool=schedule_pool(schedule, settings),
                    submit_grace_minutes=schedule["submit_grace_minutes"],
                    schedule_id=schedule["id"],
                )


# Kept for callers/tests written before schedules moved into the DB.
ensure_daily_windows = ensure_recurring_windows


def drop_unstarted_windows(db: Database, schedule_id: int, at: int) -> int:
    """Delete a schedule's windows that haven't opened yet and have no runs, so edits apply right away."""
    with db.lock:
        cur = db.execute(
            "DELETE FROM windows WHERE schedule_id = ? AND starts_at > ?"
            " AND NOT EXISTS (SELECT 1 FROM runs WHERE runs.window_id = windows.id)",
            (schedule_id, at),
        )
        return cur.rowcount


# ---------- queries ----------


def current_window(db: Database, at: int) -> dict | None:
    row = db.one(
        "SELECT * FROM windows WHERE starts_at <= ? AND ends_at > ? ORDER BY starts_at LIMIT 1", (at, at)
    )
    return dict(row) if row else None


def next_window(db: Database, at: int) -> dict | None:
    row = db.one("SELECT * FROM windows WHERE starts_at > ? ORDER BY starts_at LIMIT 1", (at,))
    return dict(row) if row else None


def public_window(window: dict, at: int, *, include_setup_key: bool) -> dict:
    """What clients may see about a window. The run seed is only revealed after the submit deadline."""
    out = {
        "id": window["id"],
        "kind": window["kind"],
        "starts_at": window["starts_at"],
        "ends_at": window["ends_at"],
        "submit_deadline": window["submit_deadline"],
        "game_version": window["game_version"],
        "character": window["character"],
        "game_mode": "dread",
    }
    if include_setup_key:
        out["setup_key"] = window["setup_key"]
    if at >= window["submit_deadline"]:
        out["seed"] = window["seed"]
    return out
